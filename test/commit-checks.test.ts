/*
 * Exercise only the hook and range CLI entrances in isolated Git repositories.
 * Cover message rule boundaries, editor cleanup, detached HEAD, real merges,
 * final message preservation, range boundaries and Chinese CLI diagnostics.
 * No internal checker functions are imported or tested.
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterEach, beforeEach, expect, test } from 'vitest';

const hook = resolve('scripts/commit-msg.ts');
const range = resolve('scripts/check-commit-range.ts');
const valid = 'feat(scripts): 检查提交信息\n\n- 增加检查并验证。\n\nRefs: #36\nRole: engineering';
let root: string;
let serial: number;
let env: NodeJS.ProcessEnv;

function git(...args: string[]): string {
  return execFileSync('git', args, { cwd: root, env, encoding: 'utf8', stdio: 'pipe' }).trim();
}

function run(command: string, ...args: string[]) {
  const result = spawnSync(process.execPath, [command, ...args], { cwd: root, env, encoding: 'utf8' });
  expect(result.error).toBeUndefined();
  return { ...result, output: result.stdout + result.stderr };
}

function check(message = valid, branch = 'ticket/36') {
  git('symbolic-ref', 'HEAD', `refs/heads/${branch}`);
  const path = join(root, 'message');
  writeFileSync(path, message);
  return run(hook, path);
}

function commit(message: string): string {
  const file = `file-${serial++}.txt`;
  writeFileSync(join(root, file), message);
  git('add', '--', file);
  git('commit', '--quiet', '--cleanup=verbatim', '-m', message, '--', file);
  return git('rev-parse', 'HEAD');
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'ds-commits-'));
  serial = 0;
  env = { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1' };
  git('init', '--quiet', '--initial-branch=main');
  git('config', 'user.name', 'Fixture');
  git('config', 'user.email', 'fixture@example.test');
  git('config', 'commit.gpgsign', 'false');
  git('config', 'core.hooksPath', '/dev/null');
});

afterEach(() => rmSync(root, { recursive: true, force: true }));

test.each(['feat', 'fix', 'docs', 'refactor', 'test', 'build', 'chore'])('hook accepts type %s', (type) => {
  expect(check(valid.replace('feat(', `${type}(`)).status).toBe(0);
});

test.each(['Repo', 'scripts/qa', 'my_scope', '范围', 'has space'])('hook accepts unrestricted nonempty scope %s', (scope) => {
  expect(check(valid.replace('(scripts)', `(${scope})`)).status).toBe(0);
});

test.each([
  [valid.replace('feat(', 'perf('), '类型只能是'],
  [valid.replace('(scripts)', '()'), '范围必写'],
  [valid.replace('(scripts)', '(  )'), '范围必写'],
  [valid.replace('(scripts)', ''), '范围必写'],
  [valid.replace('检查提交信息', 'Check messages'), '摘要至少包含一个中文字符'],
  [valid.replace('(scripts): 检查提交信息', '(中文): English'), '摘要至少包含一个中文字符'],
  [valid.replace('): ', ')： '), '中文冒号'],
  [valid.replace('): ', '):'), '冒号后接一个空格'],
  [valid.replace('): ', '):  '), '冒号后接一个空格'],
  [valid.replace('\n\n- 增加检查并验证。', ''), '正文必写'],
  [valid.replace('信息\n\n-', '信息\n-'), '正文必写'],
  [`${valid}\nReviewed: yes`, '尾注段只允许'],
  [`${valid}\n更多说明`, 'Refs 和 Role 要放在最后同一段'],
  [valid.replace('Role: engineering', 'Role: developer'), 'Role 必写且只能写一项'],
  [valid.replace('\nRole: engineering', ''), 'Role 必写且只能写一项'],
  [`${valid}\nRole: design`, 'Role 必写且只能写一项'],
  [valid.replace('Refs: #36', 'Refs: invalid'), 'Refs: #<号>'],
  [valid.replace('Refs: #36\nRole', 'Refs: #36\n\nRole'), 'Refs 和 Role 要放在最后同一段'],
])('hook rejects invalid message %# with Chinese explanation', (message, diagnostic) => {
  const result = check(message);
  expect(result.status).toBe(1);
  expect(result.stderr).toContain(diagnostic);
});

test.each(['Co-Authored-By:', 'sIgNeD-oFf-bY:', 'Reviewed-by:', 'Custom-by:', 'Generated with', 'gEnErAtEd BY'])('hook rejects signature %s even inside body', (signature) => {
  const result = check(valid.replace('- 增加检查并验证。', `🤖 * ${signature} Agent`));
  expect(result.status).toBe(1);
  expect(result.stderr).toContain('署名');
});

test('hook reports all applicable rules at once', () => {
  const result = check('bad\n\nGenerated by Agent');
  expect(result.status).toBe(1);
  for (const rule of ['a', 'b', 'c', 'e', 'f', 'g']) expect(result.stderr).toContain(`规则 ${rule}：`);
});

test('hook allows multi-paragraph body, design role, multiple refs and CRLF', () => {
  const message = valid.replace('- 增加检查并验证。', '原因：建立护栏。\n\nValidation: 验证通过。')
    .replace('Refs: #36\nRole: engineering', 'Role: design\nRefs: #36\nRefs: #32');
  expect(check(`\n${message}\n\n`.replaceAll('\n', '\r\n')).status).toBe(0);
});

test.each(['spec/32-guardrails', 'ticket/36'])('hook requires refs on %s', (branch) => {
  const result = check(valid.replace('Refs: #36\n', ''), branch);
  expect(result.status).toBe(1);
  expect(result.stderr).toContain('spec/* 和 ticket/*');
});

test.each(['main', 'spec-other', 'ticket-other'])('hook allows missing refs on %s', (branch) => {
  expect(check(valid.replace('Refs: #36\n', ''), branch).status).toBe(0);
});

test('hook allows missing refs in detached HEAD', () => {
  commit('invalid baseline');
  git('checkout', '--quiet', '--detach');
  const path = join(root, 'message');
  writeFileSync(path, valid.replace('Refs: #36\n', ''));
  expect(run(hook, path).status).toBe(0);
});

test('hook removes editor comments and truncates scissors content', () => {
  const message = `# Generated by Agent\n${valid}\n# editor comment\n# ------------------------ >8 ------------------------\nSigned-off-by: Agent\n\ninvalid diff`;
  expect(check(message).status).toBe(0);
  expect(check(valid.replace('- 增加检查并验证。', '# body comment')).stderr).toContain('正文必写');
  expect(check(valid.replace('Refs: #36', '# Refs: #36')).stderr).toContain('规则 g：');
  expect(check(valid.replace('Role: engineering', '# Role: engineering')).stderr).toContain('规则 e：');
  expect(check(valid.replace('- 增加检查并验证。', ' # Generated by Agent')).stderr).toContain('规则 f：');
});

test('hook skips a real merge in progress while range skips only actual merge commits', () => {
  const base = commit('invalid baseline outside range');
  git('checkout', '--quiet', '-b', 'topic');
  const topic = commit(valid.replace('- 增加检查并验证。', '# 最终正文保留。'));
  git('checkout', '--quiet', 'main');
  const main = commit(valid);
  git('merge', '--no-ff', '--no-commit', 'topic');
  const path = join(root, 'message');
  writeFileSync(path, 'invalid merge');
  expect(run(hook, path).status).toBe(0);
  git('commit', '--quiet', '-m', 'invalid merge');
  const merge = git('rev-parse', 'HEAD');
  const result = run(range, base, 'spec/32');
  expect(result.status, result.output).toBe(0);
  expect(result.stdout).toContain('检查通过：2 个非合并提交');
  expect(result.stdout).toContain(topic);
  expect(result.stdout).toContain(main);
  expect(result.output).not.toContain(merge);
  expect(result.output).not.toContain(`通过：${base}`);
});

test('range reports every bad commit and preserves final hash comments and scissors', () => {
  const base = commit('invalid baseline outside range');
  const good = commit(valid);
  const fakeMerge = commit('Merge branch topic');
  const signature = commit(valid.replace('- 增加检查并验证。', '# Signed-off-by: Agent'));
  const scissors = commit(`${valid}\n# ------------------------ >8 ------------------------\nGenerated by Agent`);
  const result = run(range, base, 'ticket/36');
  expect(result.status).toBe(1);
  expect(result.stdout).toContain(`通过：${good}`);
  for (const hash of [fakeMerge, signature, scissors]) expect(result.stderr).toContain(`未通过：${hash}`);
  expect(result.stderr).toContain('规则 f：');
  expect(result.stderr).toContain('检查未通过：3/4 个非合并提交');
});

test('range uses explicit source branch even in detached HEAD and permits an empty range', () => {
  const base = commit('invalid baseline outside range');
  expect(run(range, base, 'ticket/36').stdout).toContain('0 个非合并提交');
  commit(valid.replace('Refs: #36\n', ''));
  git('checkout', '--quiet', '--detach');
  expect(run(range, base, 'main').status).toBe(0);
  for (const branch of ['spec/32', 'ticket/36']) {
    const result = run(range, base, branch);
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('规则 g：');
    expect(result.stderr).toContain(`分支 ${branch}`);
  }
});

test('entrances use exit 2 for bad arguments or environment and 0 for help', () => {
  const base = commit('baseline');
  for (const command of [hook, range]) {
    expect(run(command, '--help').status).toBe(0);
    expect(run(command).status).toBe(2);
    expect(run(command).stderr).toContain('用法：');
  }
  expect(run(hook, 'missing-file').status).toBe(2);
  expect(run(hook, 'one', 'extra').stderr).toContain('请提供一个提交信息文件');
  for (const args of [[base], [base, ''], [base, 'ticket/36', 'extra']]) {
    expect(run(range, ...args).status).toBe(2);
  }
  for (const revision of ['missing-ref', '--all', `${base}..HEAD`]) {
    const result = run(range, revision, 'ticket/36');
    expect(result.status).toBe(2);
    expect(result.stderr).toContain('出错：');
  }
});
